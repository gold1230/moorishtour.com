/**
 * Public diagnostic only. No credentials, DNS writes or cache changes.
 * Run: npm run audit:delivery
 */
import { resolveTxt } from 'node:dns/promises';

const host = 'moorishtour.com';
const origin = `https://${host}`;
const endpoints = ['/', '/contact/', '/404javascript.js', '/images/tripadvisor-desert-trips.png'];
let issues = 0;
console.log('Moorish Tour public email/security/performance audit');
try {
  const txt = (await resolveTxt(host)).map(parts => parts.join(''));
  const spf = txt.filter(record => /^v=spf1(?:\s|$)/i.test(record));
  console.log(`SPF records at ${host}: ${spf.length}`);
  spf.forEach(record => console.log(`  ${record}`));
  if (spf.length !== 1) { issues++; console.warn('  ACTION: Make sure exactly one SPF TXT record exists at this hostname.'); }
} catch (error) {
  issues++; console.warn('SPF check unavailable:', error.message);
}
for (const uri of endpoints) {
  try {
    const response = await fetch(`${origin}${uri}`, {
      redirect: 'manual',
      headers: {'user-agent':'MoorishTour-DeliveryAudit/1.0'},
      signal: AbortSignal.timeout(12000),
    });
    const headers = response.headers;
    const csp = headers.get('content-security-policy') ?? '';
    const cache = headers.get('cache-control') ?? '(missing)';
    const encoding = headers.get('content-encoding') ?? '(none)';
    const cf = headers.get('cf-cache-status') ?? '(none)';
    console.log(`${uri}: HTTP ${response.status}; encoding=${encoding}; cache=${cache}; cf-cache=${cf}`);
    if (!csp && !uri.startsWith('/images/')) {
      issues++; console.warn(`  WARNING: no CSP on ${uri} (might be generated by Cloudflare or another proxy).`);
    } else if (csp && !['script-src','object-src','base-uri','frame-src'].every(v => csp.includes(v))) {
      issues++; console.warn('  WARNING: an expected CSP directive was not found in this response.');
    }
  } catch (error) {
    issues++; console.warn(`${uri}: not reachable: ${error.message}`);
  }
}
console.log(`Done. ${issues} item(s) to review. This audit does not edit DNS or Cloudflare settings.`);
